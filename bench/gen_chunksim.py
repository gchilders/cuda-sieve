#
# Builds chunksim.cpp: the cofactor chunk controller, LIFTED verbatim out of
# cofq_flush and compiled for the host, so it can be driven over thousands of
# synthetic device responses with no GPU at all.
#
# WHY LIFT RATHER THAN REIMPLEMENT. A hand-written model of this controller
# would be a second copy that drifts, and a drifting model reports on code that
# is not the code. Everything between the anchors below is the SHIPPING text,
# byte for byte; only the surroundings are stubs. The anchors are asserted, so
# a change to cofq_flush's shape fails here loudly instead of silently testing
# something else -- the discipline the generators in metal/ already use.
#
# It also reaches the branches chunkcheck.sh cannot: chunkcheck needs an NVIDIA
# card and a 200-q band and can only exercise whatever trajectory that card
# happens to produce, while this drives every device model on purpose.
import sys, re

HARNESS = r'''/* GENERATED by gen_chunksim.py -- do not edit. See that file for why the
 * controller is LIFTED from cofq_flush rather than reimplemented here. */
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cmath>
#include <cstring>

#ifndef COF_LAUNCH_TARGET_MS
#define COF_LAUNCH_TARGET_MS  1000.0f
#endif
#ifndef COF_CHUNK_HARD_FLOOR
#define COF_CHUNK_HARD_FLOOR  1024u
#endif
#define COF_CHUNK_TARGET_MS   250.0f
#define COF_FLUSH_CK(x) do { (void)(x); } while (0)
#define COFAC_THREADS_MAX 256

typedef struct {
    /* Both spellings: the current controller calls it eff_prev_valve (the
     * SLICE), the pre-fix one called it chunk_prev_valve (the chunk). Carrying
     * both lets the same harness compile either revision, which is what makes
     * a genuine control possible. */
    uint32_t chunk_cur, chunk_ceiling, eff_prev_valve, chunk_prev_valve, cap;
    float    ms_prev_valve;
    int      valve_parked;
} cofq_t;
typedef struct { uint32_t chunk; } sim_set_t;

static uint32_t cof_chunk_floor(int blocks, int threads)
{
    if (threads > COFAC_THREADS_MAX) threads = COFAC_THREADS_MAX;
    const uint64_t f = (uint64_t)(blocks > 0 ? blocks : 1)
                     * (uint64_t)(threads > 0 ? threads : 1);
    return f > 0xffffffffull ? 0xffffffffu : (uint32_t)f;
}

static int g_reports;
static uint32_t g_last_report;
static void cof_report_chunk(uint32_t c, uint32_t n, int pinned)
{ (void)pinned; g_reports++; g_last_report = c < n ? c : n; }

static int g_quiet = 1;
#define fprintf sim_fprintf
static int sim_fprintf(FILE *f, const char *fmt, ...) { (void)f; (void)fmt; return 0; }

/* ---------------- the lifted controller ---------------- */
static void controller(cofq_t *Q, uint32_t n, float sim_launch_ms,
                       float t0, float t1, uint32_t chunk,
                       int blocks, int threads)
{
    sim_set_t S; S.chunk = Q->chunk_cur;
    int valve_acted = 0;
    struct { int fired; } pk0, pk1; pk0.fired = 1; pk1.fired = 0;
    (void)pk0; (void)pk1; (void)valve_acted; (void)S;
@BODY@
}
#undef fprintf

/* ---------------- device models ---------------- */
/* launch(eff) for a slice of `eff` records, in ms. */
struct Model {
    const char *name;
    double a;      /* serial floor: one ECM chain, independent of the slice */
    double b;      /* per-record term */
    double wave;   /* records per wave; below it the launch is flat (a chain) */
};
static double model_launch(const Model &m, uint32_t eff)
{
    double e = (double)eff;
    if (m.wave > 0 && e < m.wave) e = m.wave;   /* cannot go below one chain */
    return m.a + m.b * e;
}

static int g_fail, g_checks;
/* Announces BOTH ways. A check that prints only on failure is
 * indistinguishable from a check that never executed, which is how a gate ends
 * up passing vacuously -- the failure this tree has hit repeatedly. Repeated
 * checks inside a loop are counted and summarised by the caller instead. */
static void ck(int ok, const char *what, const char *detail)
{
    g_checks++;
    if (!ok) { printf("FAIL   %-46s %s\n", what, detail ? detail : ""); g_fail = 1; }
}
static void ck1(int ok, const char *what, const char *detail)
{
    g_checks++;
    if (ok) printf("PASS   %-46s %s\n", what, detail ? detail : "");
    else  { printf("FAIL   %-46s %s\n", what, detail ? detail : ""); g_fail = 1; }
}

int main(void)
{
    /* ---- 1. ARITHMETIC SAFETY: fuzz every reachable input combination ---- */
    {
        static const uint32_t chunks[] = {1u, 2u, 1023u, 1024u, 1025u, 4096u,
            33792u, 104448u, 125952u, 131072u, 196608u, 524288u, 0x7fffffffu};
        static const uint32_t ns[] = {1u, 2u, 1890u, 65536u, 130529u, 131072u};
        static const float mss[] = {1000.001f, 1001.f, 1100.f, 2400.f, 13120.f,
            25449.f, 1e6f, 1e9f};
        static const uint32_t prevs[] = {0u, 1u, 1024u, 131072u, 0xffffffffu};
        static const float pms[] = {0.f, 1.f, 1000.f, 1e9f};
        long cases = 0;
        for (size_t a = 0; a < sizeof chunks / sizeof *chunks; a++)
        for (size_t b = 0; b < sizeof ns / sizeof *ns; b++)
        for (size_t c = 0; c < sizeof mss / sizeof *mss; c++)
        for (size_t d = 0; d < sizeof prevs / sizeof *prevs; d++)
        for (size_t e = 0; e < sizeof pms / sizeof *pms; e++) {
            cofq_t Q; memset(&Q, 0, sizeof Q);
            Q.chunk_cur = chunks[a]; Q.cap = 131072u;
            Q.eff_prev_valve = prevs[d]; Q.ms_prev_valve = pms[e];
            const uint32_t before = Q.chunk_cur;
            controller(&Q, ns[b], mss[c], 5000.f, 5000.f, 0u, 492, 256);
            cases++;
            char det[160];
            snprintf(det, sizeof det, "chunk %u n %u ms %g prev %u/%g -> %u",
                     before, ns[b], (double)mss[c], prevs[d], (double)pms[e],
                     Q.chunk_cur);
            ck(Q.chunk_cur >= 1u, "chunk never becomes zero", det);
            ck(Q.chunk_cur <= before, "the valve never raises the chunk", det);
            ck(!(Q.chunk_ceiling && Q.chunk_ceiling > before),
               "the ceiling never exceeds the chunk it came from", det);
            ck(std::isfinite((double)Q.ms_prev_valve), "ms_prev_valve stays finite", det);
        }
        printf("PASS   %-46s %ld cases\n", "arithmetic safety, exhaustive grid", cases);
    }

    /* ---- 2. INVARIANTS over full trajectories, every device model ---- */
    {
        static const Model models[] = {
          {"proportional, meets bound",      0.0,   0.0000200, 0},
          {"proportional, far over",         0.0,   0.0002000, 0},
          {"affine, serial 950 (reachable)", 950.0, 0.0023820, 0},
          {"affine, serial 1050 (unreach.)", 1050.0,0.0023820, 0},
          {"step: one ECM chain, flat",      2400.0,0.0000001, 1e9},
          {"wave floor at 2k records",       90.0,  0.0100000, 2000},
          {"980 Ti class, 2500 at floor",    400.0, 0.0621000, 0},
        };
        static const int blocks[] = {132, 492, 768, 2048};   /* 22, 82, 128, 341 SMs */
        for (size_t m = 0; m < sizeof models / sizeof *models; m++)
        for (size_t g = 0; g < sizeof blocks / sizeof *blocks; g++) {
            cofq_t Q; memset(&Q, 0, sizeof Q);
            Q.cap = 131072u;
            Q.chunk_cur = cof_chunk_floor(blocks[g], 256);
            const uint32_t n = 130529u;
            uint32_t seen_ceiling = 0; int spoken = 0; uint32_t after_spoke = 0;
            int parked_then_moved = 0, rose_after_speak = 0, ceil_rose = 0;
            for (int flush = 0; flush < 60; flush++) {
                const uint32_t eff = Q.chunk_cur < n ? Q.chunk_cur : n;
                const double L = model_launch(models[m], eff);
                const uint32_t was = Q.chunk_cur;
                const int was_parked = Q.valve_parked;
                const uint32_t was_ceiling = Q.chunk_ceiling;
                controller(&Q, n, (float)L, 5000.f, 5000.f, 0u, blocks[g], 256);
                if (Q.chunk_ceiling && was_ceiling && Q.chunk_ceiling > was_ceiling)
                    ceil_rose = 1;
                if (Q.chunk_ceiling) seen_ceiling = Q.chunk_ceiling;
                if (L > COF_LAUNCH_TARGET_MS) spoken = 1;
                if (spoken) { if (Q.chunk_cur > after_spoke && after_spoke) rose_after_speak = 1;
                              after_spoke = Q.chunk_cur; }
                if (was_parked && Q.chunk_cur != was) parked_then_moved = 1;
            }
            char det[200];
            snprintf(det, sizeof det, "%s / floor %u", models[m].name,
                     cof_chunk_floor(blocks[g], 256));
            ck(!ceil_rose,          "the ceiling is monotone non-increasing", det);
            ck(!rose_after_speak,   "the chunk never rises once the valve spoke", det);
            ck(!parked_then_moved,  "a parked valve never moves the chunk again", det);
            ck(Q.chunk_cur >= 1u,   "trajectory never reaches a zero chunk", det);
            (void)seen_ceiling;
        }
        printf("PASS   %-46s %zu models x %zu grids\n", "trajectory invariants",
               sizeof models / sizeof *models, sizeof blocks / sizeof *blocks);
    }

    /* ---- 3. THE THREE VALVE BRANCHES ARE ALL REACHED ---- */
    {
        int saw_descent = 0, saw_unreach = 0, saw_floor = 0;
        /* descent + unreachable: a flat (chain-bound) response */
        { cofq_t Q; memset(&Q, 0, sizeof Q); Q.cap = 131072u;
          Q.chunk_cur = 125952u;
          const Model fm = {"flat", 2400.0, 0.0000001, 1e9};
          for (int f = 0; f < 10; f++) {
              const uint32_t eff = Q.chunk_cur < 130529u ? Q.chunk_cur : 130529u;
              const uint32_t was = Q.chunk_cur; const int wp = Q.valve_parked;
              controller(&Q, 130529u, (float)model_launch(fm, eff), 5000.f, 5000.f, 0u, 492, 256);
              if (Q.chunk_cur < was) saw_descent = 1;
              if (!wp && Q.valve_parked && Q.chunk_cur == was) saw_unreach = 1;
          } }
        /* floor park: hard floor above the grid floor, so next == chunk_cur */
        { cofq_t Q; memset(&Q, 0, sizeof Q); Q.cap = 131072u;
          Q.chunk_cur = cof_chunk_floor(492, 256);
          const uint32_t was = Q.chunk_cur;
          controller(&Q, 130529u, 1232.0f, 5000.f, 5000.f, 0u, 492, 256);
          if (Q.valve_parked && Q.chunk_cur == was && !Q.eff_prev_valve) saw_floor = 1;
        }
        /* Scoped: with COF_CHUNK_HARD_FLOOR above the starting chunk there is
         * nothing to descend TO -- every candidate clamps back to chunk_cur
         * and the floor park is the only reachable branch. Asserting a descent
         * there would be asserting something the build cannot do. */
        if (COF_CHUNK_HARD_FLOOR < 125952u) {
            ck1(saw_descent, "the descent branch is reached", 0);
            ck1(saw_unreach, "the unreachable park is reached", 0);
        } else {
            printf("SKIP   %-46s %s\n", "descent / unreachable park",
                   "(hard floor above the grid: nothing to descend to)");
        }
        if (COF_CHUNK_HARD_FLOOR >= 131072u)
            ck1(saw_floor, "the floor park is reached", "(hard floor above the grid)");
        else
            printf("SKIP   %-46s %s\n", "the floor park",
                   "build with -DCOF_CHUNK_HARD_FLOOR=200000u to reach it");
    }

    /* ---- 4. THE HISTORY RESET actually clears ---- */
    {
        cofq_t Q; memset(&Q, 0, sizeof Q); Q.cap = 131072u; Q.chunk_cur = 125952u;
        controller(&Q, 130529u, 2400.f, 5000.f, 5000.f, 0u, 492, 256);
        if (COF_CHUNK_HARD_FLOOR < 125952u) {
            ck1(Q.eff_prev_valve != 0u, "a descent records its slice", 0);
            controller(&Q, 130529u, 500.f, 5000.f, 5000.f, 0u, 492, 256);
            ck1(Q.eff_prev_valve == 0u && Q.ms_prev_valve == 0.0f,
               "an in-bound flush clears the history", 0);
        } else {
            printf("SKIP   %-46s %s\n", "history record / reset",
                   "(hard floor above the grid: no descent to record)");
        }
    }

    /* ---- 5. A HEALTHY CARD IS UNTOUCHED ---- */
    {
        cofq_t Q; memset(&Q, 0, sizeof Q); Q.cap = 131072u;
        Q.chunk_cur = cof_chunk_floor(492, 256);
        const uint32_t open = Q.chunk_cur;
        for (int f = 0; f < 200; f++)
            controller(&Q, 130529u, 240.f, 5000.f, 5000.f, 0u, 492, 256);
        ck1(Q.chunk_ceiling == 0u && Q.eff_prev_valve == 0u
           && Q.ms_prev_valve == 0.0f && Q.valve_parked == 0,
           "under the bound, all four new fields stay zero", 0);
        ck1(Q.chunk_cur == open, "and the chunk trajectory is the floor, as before", 0);
    }

    if (g_fail) { printf("CHUNK CONTROLLER SIM: FAIL (%d checks)\n", g_checks); return 1; }
    printf("CHUNK CONTROLLER SIM: PASS (%d checks)\n", g_checks);
    return 0;
}
'''

import subprocess
REV = sys.argv[1] if len(sys.argv) > 1 else None
OUT = sys.argv[2] if len(sys.argv) > 2 else 'chunksim.cpp'
if REV:
    src = subprocess.check_output(['git', 'show', REV + ':bench/cofac.cuh'],
                                  cwd='..').decode()
else:
    src = open('cofac.cuh').read()

A = '    /* ---- the safety valve: an over-bound LAUNCH may descend past the floor -'
Z = '        if (Q->chunk_cur != was) cof_report_chunk(Q->chunk_cur, n, 0);\n    }\n'
ia = src.index(A)
iz = src.index(Z, ia) + len(Z)
body = src[ia:iz]

# What the lifted text is allowed to depend on. Asserted so that a new
# dependency shows up here rather than as a mysterious compile error.
assert 'COF_LAUNCH_TARGET_MS' in body and 'COF_CHUNK_HARD_FLOOR' in body
assert 'COF_CHUNK_TARGET_MS' in body and 'cof_chunk_floor' in body
assert body.count('valve_acted = 1;') == 3, 'not three valve branches'
assert 'Q->chunk_ceiling' in body
assert ('Q->eff_prev_valve' in body) or ('Q->chunk_prev_valve' in body)
assert 'pk0.fired' in body and 'pk1.fired' in body, 'event reads missing'

# The two event reads are the ONLY GPU dependency in the block. Replaced by the
# harness's injected measurement; everything else is arithmetic.
ev = ('        float pm0 = 0.0f, pm1 = 0.0f;\n'
      '        if (pk0.fired) COF_FLUSH_CK(cudaEventElapsedTime(&pm0, pk0.a, pk0.b));\n'
      '        if (pk1.fired) COF_FLUSH_CK(cudaEventElapsedTime(&pm1, pk1.a, pk1.b));\n'
      '        const float launch_ms = pm0 > pm1 ? pm0 : pm1;\n')
assert body.count(ev) == 1, 'the valve event preamble changed'
body = body.replace(ev, '        const float launch_ms = sim_launch_ms;\n', 1)
assert 'cudaEvent' not in body, 'a CUDA dependency survives in the lifted block'

open(OUT, 'w').write(HARNESS.replace('@BODY@', body))
print('wrote %s (%d lines lifted)' % (OUT, body.count(chr(10))))
